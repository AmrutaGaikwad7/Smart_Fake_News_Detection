def add_image(story, path, caption, max_width=6.6*inch, max_height=4.1*inch):
    path = Path(path)
    if not path.exists():
        return False
    img = Image(str(path))
    scale = min(max_width / img.imageWidth, max_height / img.imageHeight, 1)
    img.drawWidth = img.imageWidth * scale
    img.drawHeight = img.imageHeight * scale
    story.append(img)
    story.append(Paragraph(caption, styles["CaptionCustom"]))
    story.append(Spacer(1, 10))
    return True

